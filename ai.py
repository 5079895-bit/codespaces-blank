def _extract_json(content: str):
    if not content:
        return None
    start = content.find("{")
    end = content.rfind("}")
    if start == -1 or end == -1 or end <= start:
        return None
    try:
        return json.loads(content[start:end + 1])
    except json.JSONDecodeError as e:
        logger.warning("Не удалось распарсить JSON: %s | сырой ответ: %r", e, content[:200])
        return None


