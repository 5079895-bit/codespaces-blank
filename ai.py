def analyze_photo(file_path):
    """Возвращает: {"is_food": bool, "description": str, "is_compound": bool}"""
    try:
        with open(file_path, "rb") as image_file:
            encoded_string = base64.b64encode(image_file.read()).decode("utf-8")

        response = client.chat.completions.create(
            model="deepseek-chat",
            messages=[
                {
                    "role": "user",
                    "content": [
                        {"type": "text", "text": (
                            "Посмотри на фото. Если это упаковка с составом — выпиши КБЖУ на 100г и общий вес.\n"
                            "Если это просто еда — опиши, что видно.\n"
                            "ВАЖНО: Описывай ТОЛЬКО еду и посуду, в которой она находится. Никакой обстановки, фона, скатертей, салфеток, столов, пакетиков рядом. Пример: 'Тарелка с супом', 'Кружка с чаем', 'Креманка с мороженым', 'Тарелка с котлетой и пюре'.\n"
                            "Определи, это одно простое блюдо (яблоко, тарелка супа) или сложный поднос/составное блюдо (картошка с котлетой, несколько тарелок).\n"
                            "Формат ответа (строго):\n"
                            "еда: да или нет\n"
                            "составное: да или нет\n"
                            "описание: краткое описание (перечисли всё, что видишь)\n"
                        )},
                        {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{encoded_string}"}},
                    ],
                }
            ],
            temperature=0.1,
        )
        content = response.choices[0].message.content or ""
        logger.info("DeepSeek увидел: %s", content)

        is_food = False
        is_compound = False
        description = ""

        for line in content.splitlines():
            line = line.strip()
            low = line.lower()
            if low.startswith("еда:"):
                is_food = low.split(":", 1)[1].strip().startswith("да")
            elif low.startswith("составное:"):
                is_compound = low.split(":", 1)[1].strip().startswith("да")
            elif low.startswith("описание:"):
                description = line.split(":", 1)[1].strip()

        return {"is_food": is_food, "is_compound": is_compound, "description": description}
    except Exception as e:
        logger.exception("Ошибка ИИ (analyze_photo): %s", e)
        return {"is_food": False, "is_compound": False, "description": ""}


